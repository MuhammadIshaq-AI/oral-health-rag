"""Fixed safety messages and call-to-action buttons for each triage label.

These are deliberately short, templated and reviewed — they are never
generated by the LLM. Phone numbers: 000 (Australian emergency), healthdirect
1800 022 222, Lifeline 13 11 14, Suicide Call Back Service 1300 659 467.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from app.rag.prompt import DISCLAIMER
from app.safety.labels import Label

