HEALTHDIRECT = {"label": "healthdirect 1800 022 222", "href": "tel:1800022222", "kind": "info"}
LIFELINE = {"label": "Lifeline 13 11 14", "href": "tel:131114", "kind": "crisis"}
LIFELINE_TEXT = {"label": "Text Lifeline 0477 13 11 14", "href": "sms:0477131114", "kind": "crisis"}
SCBS = {
    "label": "Suicide Call Back Service 1300 659 467",
    "href": "tel:1300659467",
    "kind": "crisis",
}


@dataclass(frozen=True)
class SafetyTemplate:
    """Banner title, body text and actions for a label."""

    title: str
    message: str
    actions: list[dict[str, str]] = field(default_factory=list)


