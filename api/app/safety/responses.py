#: Used only when corpus retrieval for first aid fails. Content mirrors the ADA
#: and healthdirect knocked-out tooth guidance and must be re-checked when the
#: corpus is updated.
AVULSION_FALLBACK = (
    "**If an adult tooth is knocked out:**\n"
    "- Find the tooth and hold it by the crown (the white part), not the root.\n"
    "- If it is dirty, rinse it briefly in milk or saline. Do not scrub it.\n"
    "- If you can, gently put it back in its socket and bite on a clean cloth to hold it.\n"
    "- If you can't, keep it in milk or in the person's saliva (inside the cheek), not in water.\n"
    "- See a dentist within 30 to 60 minutes.\n"
    "- Do not put a baby tooth back in.\n\n"
    f"{DISCLAIMER}"
)

AVULSION_QUERY = "knocked out adult tooth first aid hold by crown store in milk see dentist"


def halted_message(label: Label) -> str:
    """Full reply text for labels that stop the dental flow."""
    t = TEMPLATES[label]
    return f"**{t.title}**\n\n{t.message}"
